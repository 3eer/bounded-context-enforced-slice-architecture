function autoGenHeader(): string {
  return "// AUTO-GENERATED by besa generate. DO NOT EDIT.\n";
}

function collectCrossContextVias(
  config: BesaConfig
): Map<string, { via: string; fromContext: string; toContext: string }> {
  const map = new Map<
    string,
    { via: string; fromContext: string; toContext: string }
  >();
  for (const [ctxName, ctx] of Object.entries(config.contexts)) {
    for (const ccr of ctx.cross_context_reads ?? []) {
      if (!map.has(ccr.via)) {
        map.set(ccr.via, {
          via: ccr.via,
          fromContext: ctxName,
          toContext: ccr.context,
        });
      }
    }
  }
  return map;
}

function getRootTypesForContext(
  config: BesaConfig,
  targetContextName: string
): string[] {
  const roots: string[] = [];
  for (const agg of Object.values(config.aggregates)) {
    if (agg.context === targetContextName) {
      roots.push(agg.root);
    }
  }
  return roots;
}

