function generateAggregateTypes(config: BesaConfig): string {
  const lines: string[] = [autoGenHeader(), ""];
  for (const agg of Object.values(config.aggregates)) {
    const names = [agg.root, ...agg.entities];
    for (const name of names) {
      lines.push(`export interface Base${name} {`);
      lines.push(`  id: string;`);
      lines.push(`  // TODO: define Base${name} fields`);
      lines.push(`}`);
      lines.push("");
    }
  }
  return lines.join("\n");
}

function generateContextScope(config: BesaConfig): string {
  const lines: string[] = [autoGenHeader(), ""];

  for (const [ctxName, ctx] of Object.entries(config.contexts)) {
    const pascal = toPascalCase(ctxName);
    const aggLiterals = ctx.aggregates.map((a) => `"${a}"`).join(" | ");
    lines.push(
      `export type ${pascal}ContextAggregates = ${aggLiterals || "never"};`
    );
  }
  lines.push("");
  lines.push("export type ContextAggregateMap = {");
  for (const [ctxName, ctx] of Object.entries(config.contexts)) {
    const pascal = toPascalCase(ctxName);
    if (ctx.aggregates.length > 0) {
      lines.push(`  ${ctxName}: ${pascal}ContextAggregates;`);
    } else {
      lines.push(`  ${ctxName}: never;`);
    }
  }
  lines.push("};");
  lines.push("");
  return lines.join("\n");
}

function generateRepository(aggName: string, rootName: string): string {
  const pascal = toPascalCase(rootName);
  const lines: string[] = [
    autoGenHeader(),
    "",
    `import type { Base${pascal} } from "../types/aggregate-types";`,
    "",
    `export interface Mutable${pascal}Repository {`,
    `  findById(id: string): Promise<Base${pascal} | null>;`,
    `  save(entity: Base${pascal}): Promise<void>;`,
    `  delete(id: string): Promise<void>;`,
    `}`,
    "",
    `export interface Readonly${pascal}Repository {`,
    `  findById(id: string): Promise<Base${pascal} | null>;`,
    `}`,
    "",
  ];
  void aggName;
  return lines.join("\n");
}

function generateMutationContract(): string {
  return [
    autoGenHeader(),
    "",
    "export type MutationFn<TInput, TOutput, TRepos extends object> = (",
    "  input: TInput,",
    "  repos: TRepos,",
    ") => Promise<TOutput>;",
    "",
    "export function defineMutation<TInput, TOutput, TRepos extends object>(",
    "  fn: MutationFn<TInput, TOutput, TRepos>,",
    "): MutationFn<TInput, TOutput, TRepos> {",
    "  return fn;",
    "}",
    "",
  ].join("\n");
}

function generateQueryContract(): string {
  return [
    autoGenHeader(),
    "",
    "export type QueryFn<TInput, TOutput, TRepos extends object> = (",
    "  input: TInput,",
    "  repos: TRepos,",
    ") => Promise<TOutput>;",
    "",
    "export function defineQuery<TInput, TOutput, TRepos extends object>(",
    "  fn: QueryFn<TInput, TOutput, TRepos>,",
    "): QueryFn<TInput, TOutput, TRepos> {",
    "  return fn;",
    "}",
    "",
  ].join("\n");
}

function generateCrossContextInterface(
  via: string,
  rootTypes: string[]
): string {
  const baseImportTypes = rootTypes.map((r) => `Base${r}`).join(", ");
  const lines: string[] = [
    autoGenHeader(),
    "",
    `import type { ${baseImportTypes} } from "../types/aggregate-types";`,
    "",
    `export interface ${via} {`,
  ];
  for (const root of rootTypes) {
    lines.push(`  findById(id: string): Promise<Base${root} | null>;`);
  }
  lines.push(`}`);
  lines.push("");
  return lines.join("\n");
}

function generateUseCaseExecuteType(
  ucPath: string,
  uc: { type: "mutation" | "query"; aggregates: string[]; cross_context_reads?: string[] | undefined },
  config: BesaConfig
): string {
  const camelName = useCaseNameToCamelCase(ucPath);
  const pascalName = toPascalCase(camelName);
  const contractFn = uc.type === "mutation" ? "defineMutation" : "defineQuery";
  const contractType = uc.type === "mutation" ? "MutationFn" : "QueryFn";

  const imports: string[] = [
    `import { ${contractFn} } from "../${uc.type === "mutation" ? "mutation" : "query"}";`,
    `import type { ${contractType} } from "../${uc.type === "mutation" ? "mutation" : "query"}";`,
  ];

  const repoEntries: string[] = [];

  for (const aggName of uc.aggregates) {
    const agg = config.aggregates[aggName];
    if (agg === undefined) continue;
    const pascal = toPascalCase(agg.root);
    const repoType = uc.type === "mutation"
      ? `Mutable${pascal}Repository`
      : `Readonly${pascal}Repository`;
    const kebab = toKebabCase(aggName);
    imports.push(`import type { ${repoType} } from "../../repositories/${kebab}-repository";`);
    repoEntries.push(`  ${aggName}: ${repoType};`);
  }

  const contextCfg = config.contexts[uc.aggregates.length > 0
    ? (config.aggregates[uc.aggregates[0]!]?.context ?? "")
    : ""];

  for (const ccrContextName of uc.cross_context_reads ?? []) {
    const ccrDecl = (contextCfg?.cross_context_reads ?? []).find(
      (c: { context: string; via: string }) => c.context === ccrContextName
    );
    if (ccrDecl === undefined) continue;
    const kebabVia = toKebabCase(ccrDecl.via);
    imports.push(`import type { ${ccrDecl.via} } from "../../cross-context/${kebabVia}-interface";`);
    repoEntries.push(`  ${toCamelCase(ccrDecl.via)}: ${ccrDecl.via};`);
  }

  const sortedImports = imports.sort((a, b) => {
    const pathA = a.match(/from "([^"]+)"/)?.[1] ?? "";
    const pathB = b.match(/from "([^"]+)"/)?.[1] ?? "";
    return pathA.localeCompare(pathB);
  });

  const repoTypeName = `${pascalName}Repos`;

  return [
    autoGenHeader(),
    "",
    ...sortedImports,
    "",
    `export type ${repoTypeName} = {`,
    ...repoEntries,
    "};",
    "",
    `export type ${pascalName}Execute = ${contractType}<unknown, unknown, ${repoTypeName}>;`,
    "",
    `export { ${contractFn} };`,
    "",
  ].join("\n");
}

function generateEslintConfig(config: BesaConfig): string {
  type BoundaryElement = { type: string; pattern: string };
  type BoundaryRule = { from: string; allow: string[] };

  const elements: BoundaryElement[] = [];
  const rules: BoundaryRule[] = [];

  for (const ctxName of Object.keys(config.contexts)) {
    elements.push({
      type: `${ctxName}-context`,
      pattern: `src/contexts/${ctxName}/**`,
    });
  }
  elements.push({ type: "infra", pattern: "src/infra/**" });
  elements.push({ type: "besa-generated", pattern: "src/besa-generated/**" });
  elements.push({ type: "shared", pattern: "src/_shared/**" });

  for (const ctxName of Object.keys(config.contexts)) {
    rules.push({
      from: `${ctxName}-context`,
      allow: ["besa-generated", "shared"],
    });
  }
  rules.push({ from: "infra", allow: ["besa-generated"] });
  rules.push({ from: "besa-generated", allow: [] });
  rules.push({ from: "shared", allow: [] });

  const eslintConfig = {
    $schema: "https://json.schemastore.org/eslintrc",
    plugins: ["boundaries"],
    settings: {
      "boundaries/elements": elements,
    },
    rules: {
      "boundaries/element-types": [
        "error",
        { default: "disallow", rules },
      ],
      "@typescript-eslint/no-explicit-any": "error",
    },
  };

  return JSON.stringify(eslintConfig, null, 2) + "\n";
}

